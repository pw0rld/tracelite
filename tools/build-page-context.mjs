// Bundle our own functions into one self-contained Chrome executeScript function.
// No runtime eval, remote source, or page-visible configuration object is used.
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { applyPageLocale } from "../extension/page-locale.js";
import { installFrameLocale } from "../extension/frame-locale.js";
import { installWorkerLocale } from "../extension/worker-locale.js";
import { EARLY_PROFILES, earlyControlEvent } from "../extension/region-early.js";

export function renderPageContext() {
  return `// Generated by tools/build-page-context.mjs; edit the source modules instead.\nexport function applyPageContext(profile, controlEvent) {
  "use strict";
  ${applyPageLocale.toString()}
  ${installFrameLocale.toString()}
  ${installWorkerLocale.toString()}
  const root = globalThis, documents = new WeakMap(), cleanups = new Set();
  let active = true;
  function visit(win) {
    if (!active) return null;
    let doc;
    try { doc = win.document; if (!doc) return null; } catch { return null; }
    if (documents.has(doc)) return documents.get(doc).result;
    let result;
    try { result = applyPageLocale(profile, win); } catch { return null; }
    const entry = { result, stop: [] };
    documents.set(doc, entry);
    // Matching values also covers a realm already patched by another authorized
    // document controller. Do not wrap it twice or claim ownership of its hooks.
    if (!result.changed || cleanups.size >= 512) return result;
    cleanups.add(new WeakRef(entry));
    try { entry.stop.push(installFrameLocale(win, visit)); } catch {}
    try { entry.stop.push(installWorkerLocale(win, profile, applyPageLocale)); } catch {}
    try { for (let i = 0; i < win.frames.length; i++) visit(win.frames[i]); } catch {}
    return result;
  }
  function stop() {
    if (!active) return;
    active = false;
    for (const reference of cleanups) {
      const entry = reference.deref();
      if (entry) for (const dispose of entry.stop) { try { dispose(); } catch {} }
    }
    cleanups.clear();
    if (typeof controlEvent === "string") root.removeEventListener(controlEvent, stop);
    root.removeEventListener("pagehide", onPageHide);
  }
  function onPageHide(event) {
    // A BFCache entry retains this Document and its patched API objects. Keep
    // its matching hooks too; the isolated bootstrap rechecks authorization on
    // persisted pageshow and can deliver a stop-only event if it went stale.
    if (!event.persisted) stop();
  }
  if (typeof controlEvent === "string" && /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i.test(controlEvent)) {
    root.addEventListener(controlEvent, stop, { once: true });
  }
  root.addEventListener("pagehide", onPageHide);
  const result = visit(root);
  if (!result?.changed) stop();
  return result ? { ...result, version: 5 } : { applied: false };
}
`;
}

export function renderEarlyEntry(key) {
  const entry = EARLY_PROFILES.find(candidate => candidate.key === key);
  if (!entry) throw new TypeError("Unknown early profile");
  const context = renderPageContext().replace(/^\/\/[^\n]*\n/, "").replace("export function applyPageContext", "function applyPageContext");
  return `// Generated by tools/build-page-context.mjs; fixed ${entry.key} MAIN document_start entry.\n(() => {
  "use strict";
  ${context}
  ${earlyControlEvent.toString()}
  try {
    applyPageContext(${JSON.stringify(entry.profile)}, earlyControlEvent(${JSON.stringify(entry.key)}, performance.timeOrigin));
  } catch { /* The extension verifies actual page readings separately. */ }
})();\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("../extension/page-context.js", import.meta.url), renderPageContext());
  await mkdir(new URL("../extension/early/", import.meta.url), { recursive: true });
  for (const entry of EARLY_PROFILES) await writeFile(new URL(`../extension/${entry.file}`, import.meta.url), renderEarlyEntry(entry.key));
  console.log(`Updated extension/page-context.js and ${EARLY_PROFILES.length} early MAIN entries`);
}
